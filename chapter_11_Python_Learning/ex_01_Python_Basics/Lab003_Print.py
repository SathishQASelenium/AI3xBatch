print("Hello", "World")
# sep -> is the separator between the strings, by default it is a space
# end -> is the string appended after the last value, by default it is a newline character. here we are using tab character as end
print("Hello", "World", "TheTestingAcademy", sep="*", end="\t")
# In below example we are using "-" as separator between the strings
print("Hello", "World", sep="-")
# In below example we are using "-" as separator between the strings
print("*", "*", sep="-")
