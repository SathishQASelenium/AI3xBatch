# _ is a valid identifier in Python, but it is not recommended to use it as a variable name because it can lead to confusion. 
# In Python, a single underscore is often used to indicate that a variable is intended for internal use or is a temporary variable.
_ = 12
print(_)
_ = _ + 1
print(_)

